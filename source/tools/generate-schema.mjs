import {readFile,readdir,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';

// Split migration files without splitting SQL string literals or comments.
function statements(sql){
 const result=[];let text='',quote=null;
 for(let i=0;i<sql.length;i++){
  const c=sql[i],next=sql[i+1];
  if(quote){text+=c;if(c===quote){if(next===quote){text+=next;i++;}else quote=null;}continue;}
  if(c==='-'&&next==='-'){while(i<sql.length&&sql[i]!=='\n')i++;text+='\n';continue;}
  if(c==='/'&&next==='*'){i+=2;while(i<sql.length&&!(sql[i]==='*'&&sql[i+1]==='/'))i++;i++;text+=' ';continue;}
  if(c==="'"||c==='"'||c==='`'){quote=c;text+=c;continue;}
  if(c===';'){if(text.trim())result.push(text.trim());text='';}else text+=c;
 }
 if(quote)throw new Error('Unclosed SQL string in migration.');
 if(text.trim())result.push(text.trim());return result;
}
export async function generateSchema(){
 const directory=new URL('../migrations/',import.meta.url),migrations=[];
 for(const name of (await readdir(directory)).filter(x=>/^\d+[-_].*\.sql$/.test(x)).sort()){
  const sql=(await readFile(new URL(name,directory),'utf8')).replace(/\r\n?/g,'\n');
  migrations.push({id:name,checksum:createHash('sha256').update(sql).digest('hex'),statements:statements(sql)});
 }
 if(!migrations.length)throw new Error('No database migrations found.');
 const output='// Generated by tools/generate-schema.mjs. Edit migrations, then rebuild.\nexport const migrations = '+JSON.stringify(migrations,null,2)+';\n';
 await writeFile(new URL('../src/schema.generated.js',import.meta.url),output);
}
await generateSchema();
